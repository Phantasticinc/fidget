import asyncio
from playwright.async_api import async_playwright
from PIL import Image
U='http://localhost:8766/fidget/'
MOCK="""window.__shares=[];navigator.share=async d=>{window.__shares.push({t:d.text,u:d.url,files:(d.files||[]).length});};navigator.canShare=d=>true;"""
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(); fails=[]; shots=[]
    ctx=await b.new_context(viewport={'width':412,'height':915},device_scale_factor=2)
    await ctx.add_init_script(MOCK); pg=await ctx.new_page()
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.on('dialog',lambda d: asyncio.ensure_future(d.accept()))
    await pg.goto(U); await pg.wait_for_timeout(1200)
    await pg.click('#shopBtn'); await pg.wait_for_timeout(500)
    await pg.locator('#giftCard').scroll_into_view_if_needed(); await pg.wait_for_timeout(300)
    s='preview/share/1-card.png'; await pg.screenshot(path=s); shots.append(s)
    if await pg.inner_text('#giftShare')!='Share Fidget': fails.append('btn label')
    await pg.click('#giftShare'); await pg.wait_for_timeout(1200)
    if not await pg.is_visible('#gift'): fails.append('picker not shown')
    s='preview/share/2-picker.png'; await pg.screenshot(path=s); shots.append(s)
    n=await pg.locator('#giftList .item').count(); print('picker items',n)
    await pg.click('#giftList .item[data-id="spin_plasma"] button'); await pg.wait_for_timeout(900)
    s='preview/share/3-reveal.png'; await pg.screenshot(path=s); shots.append(s)
    st=await pg.evaluate("""async()=>{const e=await import('./js/store/ent.js?v=6');const r={gift:e.gifted(),has:e.has('spin_plasma'),other:e.has('spin_aurora')};e.set([]);r.afterRestore=e.has('spin_plasma');r.again=e.setGift('pop_pack_lava');r.toy=localStorage.getItem('fidget.toy');return r}""")
    print(st, await pg.evaluate('window.__shares'))
    if st!={'gift':'spin_plasma','has':True,'other':False,'afterRestore':True,'again':False,'toy':'spin'}: fails.append('state '+str(st))
    await pg.click('#giftReveal button'); await pg.wait_for_timeout(1500)
    s='preview/share/4-playing.png'; await pg.screenshot(path=s); shots.append(s)
    await pg.reload(); await pg.wait_for_timeout(1200); await pg.click('#shopBtn'); await pg.wait_for_timeout(400)
    t=await pg.inner_text('#giftCard'); print('after reload:',t)
    if 'Plasma' not in t: fails.append('persist')
    await pg.click('#shop [data-close]')
    await pg.evaluate("window.__fidget.record.fake('streak',120,80)"); await pg.wait_for_timeout(3200)
    if not await pg.is_visible('#cbShare'): fails.append('celeb share hidden')
    s='preview/share/5-celeb-share.png'; await pg.screenshot(path=s); shots.append(s)
    await pg.click('#cbShare'); await pg.wait_for_timeout(1200)
    sh=await pg.evaluate('window.__shares'); print('shares',sh)
    if len(sh)!=1 or sh[0]['files']!=1: fails.append('celeb share image')
    # fallback: no navigator.share
    c2=await b.new_context(viewport={'width':412,'height':915},device_scale_factor=2,permissions=['clipboard-read','clipboard-write'])
    await c2.add_init_script("delete Navigator.prototype.share; delete Navigator.prototype.canShare;")
    q=await c2.new_page(); q.on('pageerror',lambda e:errs.append(str(e))); q.on('dialog',lambda d: asyncio.ensure_future(d.accept()))
    await q.goto(U); await q.wait_for_timeout(1000); await q.click('#shopBtn'); await q.wait_for_timeout(400)
    lab=await q.inner_text('#giftShare'); print('fallback label',lab)
    if lab!='Copy link to share': fails.append('fallback label')
    await q.click('#giftShare'); await q.wait_for_timeout(500)
    clip=await q.evaluate('navigator.clipboard.readText()'); print('clip',clip)
    if 'phantasticinc.github.io/fidget' not in clip: fails.append('copy')
    if not await q.is_visible('#gift'): fails.append('fallback picker')
    s='preview/share/6-copy-fallback.png'; await q.screenshot(path=s); shots.append(s)
    ims=[Image.open(x).resize((412,915)) for x in shots]; c=Image.new('RGB',(412*len(ims),915))
    for i,im in enumerate(ims): c.paste(im,(412*i,0))
    c.save('preview/share-to-unlock.png')
    fails+=errs; print('FAILS',fails); await b.close()
asyncio.run(main())
