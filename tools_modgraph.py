# Prints the static ES-module import graph reachable from js/main.js (exact URLs incl. ?v=), for <link rel=modulepreload>.
import re,os,posixpath,sys
root=os.path.dirname(os.path.abspath(__file__))
seen=[];
def walk(u):
  if u in seen: return
  seen.append(u); path=os.path.join(root,u.split('?')[0])
  src=open(path).read()
  for m in re.finditer(r"""^\s*import\s+(?:[^'"]*?\sfrom\s+)?['"]([^'"]+)['"]""",src,re.M):
    walk(posixpath.normpath(posixpath.join(posixpath.dirname(u.split('?')[0]),m.group(1).split('?')[0]))+('?'+m.group(1).split('?')[1] if '?' in m.group(1) else ''))
m=re.search(r'src="(js/main\.js[^"]*)"',open(os.path.join(root,'index.html')).read()).group(1)
walk(m)
if "--write" not in sys.argv: print("\n".join(seen[1:]))
# --write: refresh the <!-- modulepreload --> block in index.html
if '--write' in sys.argv:
  p=os.path.join(root,'index.html');h=open(p).read()
  blk='<!-- modulepreload:start (generated by tools_modgraph.py --write) -->\n'+''.join(f'<link rel="modulepreload" href="{u}">\n' for u in [m]+seen[1:])+'<!-- modulepreload:end -->\n'
  if 'modulepreload:start' in h: h=re.sub(r'<!-- modulepreload:start.*?<!-- modulepreload:end -->\n',lambda _:blk,h,flags=re.S)
  else: h=h.replace('<link rel="manifest"',blk+'<link rel="manifest"',1)
  open(p,'w').write(h)
